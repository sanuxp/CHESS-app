#!/usr/bin/env python3
"""Generates every app icon from the logo SVGs in docs/logo.

    python tools/make_icons.py            # default (gold) logo
    python tools/make_icons.py halloween  # seasonal edition

Needs Pillow (pip install pillow) and Google Chrome or Edge (used only to rasterise the SVG).
Writes:
  flutter/assets/icon/  icon_round.png (transparent), icon_square.png (opaque), icon_foreground.png (Android adaptive)
  flutter/flutter_launcher_icons.yaml  (config for the icon generator, with this variant's background colour)
  cpp/app/res/chess.ico (multi-size, embedded in chess.exe by chess.rc)
  docs/logo/final/      the same PNGs for reference
Then apply the Flutter icons with:  cd flutter && dart run flutter_launcher_icons
"""
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LOGO = ROOT / "docs" / "logo"

VARIANTS = {
    "default": {"svg": LOGO / "logo-simple.svg", "background": "#1a0f05"},
    "halloween": {"svg": LOGO / "logo-halloween.svg", "background": "#0c0509"},
}

CHROME_CANDIDATES = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
]


def find_browser():
    for c in CHROME_CANDIDATES:
        if os.path.exists(c):
            return c
    sys.exit("Chrome or Edge not found; it is needed to rasterise the SVG.")


def render(svg: Path, out: Path, scale: float, background: str | None, size: int = 1024):
    """Rasterises the SVG at `scale` of the canvas, centred, on a transparent or solid background."""
    pct = scale * 100
    bg = background or "transparent"
    html = f"""<!doctype html><html><body style="margin:0;background:{bg}">
    <div style="width:{size}px;height:{size}px;display:flex;align-items:center;justify-content:center">
    <img src="{svg.as_uri()}" style="width:{pct}%;height:{pct}%"></div></body></html>"""
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "page.html"
        page.write_text(html, encoding="utf-8")
        cmd = [
            find_browser(), "--headless=new", "--disable-gpu", "--hide-scrollbars",
            "--allow-file-access-from-files", f"--window-size={size},{size}",
            "--default-background-color=00000000", f"--screenshot={out}", page.as_uri(),
        ]
        subprocess.run(cmd, check=True, capture_output=True)
    img = Image.open(out)
    if img.size != (size, size):  # headless windows can come out slightly off
        img = img.crop((0, 0, size, size))
        img.save(out)


def main():
    variant = sys.argv[1] if len(sys.argv) > 1 else "default"
    if variant not in VARIANTS:
        sys.exit(f"unknown variant {variant!r}; choose from {', '.join(VARIANTS)}")
    cfg = VARIANTS[variant]
    final = LOGO / "final"
    final.mkdir(exist_ok=True)

    round_png = final / "icon_round.png"
    square_png = final / "icon_square.png"
    fg_png = final / "icon_foreground.png"
    render(cfg["svg"], round_png, 0.98, None)             # transparent, nearly full
    render(cfg["svg"], square_png, 0.92, cfg["background"])  # opaque square for iOS / legacy Android
    render(cfg["svg"], fg_png, 0.64, None)                 # inside the adaptive-icon safe zone

    # iOS rejects icons with transparency: flatten the square one.
    Image.open(square_png).convert("RGB").save(square_png)

    flutter_icons = ROOT / "flutter" / "assets" / "icon"
    flutter_icons.mkdir(parents=True, exist_ok=True)
    for src in (round_png, square_png, fg_png):
        shutil.copy(src, flutter_icons / src.name)
    bg = cfg["background"]
    (ROOT / "flutter" / "flutter_launcher_icons.yaml").write_text(
        "# Generated by tools/make_icons.py - do not edit by hand.\n"
        "flutter_launcher_icons:\n"
        '  image_path: "assets/icon/icon_square.png"\n'
        "  android: true\n"
        f'  adaptive_icon_background: "{bg}"\n'
        '  adaptive_icon_foreground: "assets/icon/icon_foreground.png"\n'
        "  ios: true\n"
        "  remove_alpha_ios: true\n"
        "  web:\n"
        "    generate: true\n"
        '    image_path: "assets/icon/icon_round.png"\n'
        f'    background_color: "{bg}"\n'
        f'    theme_color: "{bg}"\n'
        "  windows:\n"
        "    generate: true\n"
        '    image_path: "assets/icon/icon_round.png"\n'
        "    icon_size: 256\n",
        encoding="utf-8",
    )

    res = ROOT / "cpp" / "app" / "res"
    res.mkdir(parents=True, exist_ok=True)
    big = Image.open(round_png).convert("RGBA")
    sizes = [(s, s) for s in (16, 24, 32, 48, 64, 128, 256)]
    big.save(res / "chess.ico", format="ICO", sizes=sizes)

    print(f"variant: {variant}")
    for p in (round_png, square_png, fg_png, res / "chess.ico"):
        print(f"  {p.relative_to(ROOT)}  {p.stat().st_size / 1024:.0f} KB")
    print("Next: cd flutter && dart run flutter_launcher_icons   (then rebuild both apps)")


if __name__ == "__main__":
    main()
